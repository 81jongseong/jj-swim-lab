// 편의 함수: ID로 드릴 찾기
export function findDrillById(id: string): Drill | undefined {
  return DRILLS.find(d => d.id === id);
}

// 편의 함수: 태그로 필터링
export function getDrillsByTag(tag: string): Drill[] {
  return DRILLS.filter(d => d.tags.includes(tag));
}


